"""
Export the deployed model + a labelled replay capture for the web dashboard (web/).

  web/model.js   - pipeline parameters (from pipeline.py) + weights/threshold/normalization
                   parsed from firmware/include/model_*.h, i.e. exactly what is flashed
  web/replay.js  - one labelled test capture, so the page can replay it with ground truth

Run after train.py (which updates firmware/include), then verify_web.py.
"""

import json
import os
import sys

import numpy as np

import pipeline as P

HERE        = os.path.dirname(os.path.abspath(__file__))
INCLUDE_DIR = os.path.join(HERE, "..", "firmware", "include")
WEB_DIR     = os.path.join(HERE, "..", "web")
REPLAY_CSV  = os.path.join(HERE, "data", "test", "synthetic_test_01.csv")


def r(v, nd=9):
    return float(round(float(v), nd))


def export_model():
    layers, norm_min, norm_scale, thr = P.load_model_headers(INCLUDE_DIR)
    model = {
        "params": {
            "SAMPLE_INTERVAL_MS":  P.SAMPLE_INTERVAL_MS,
            "VALID_MIN_CM":        P.VALID_MIN_CM,
            "VALID_MAX_CM":        P.VALID_MAX_CM,
            "HAMPEL_SIZE":         P.HAMPEL_SIZE,
            "HAMPEL_K_MAD":        P.HAMPEL_K_MAD,
            "HAMPEL_MIN_CM":       P.HAMPEL_MIN_CM,
            "WINDOW_SIZE":         P.WINDOW_SIZE,
            "MAX_GAP_MS":          P.MAX_GAP_MS,
            "ALARM_ON_COUNT":      P.ALARM_ON_COUNT,
            "ALARM_OFF_COUNT":     P.ALARM_OFF_COUNT,
            "FAULT_INVALID_COUNT": P.FAULT_INVALID_COUNT,
        },
        "threshold":  r(thr),
        "norm_min":   [r(v) for v in norm_min],
        "norm_scale": [r(v) for v in norm_scale],
        "layers": [{"W": [[r(v) for v in row] for row in k], "b": [r(v) for v in b]}
                   for k, b in layers],
    }
    path = os.path.join(WEB_DIR, "model.js")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Auto-generated by training/export_web.py - DO NOT EDIT\n")
        f.write("// Same weights/threshold as firmware/include/model_*.h\n")
        f.write("var ESP32_MODEL = " + json.dumps(model, separators=(",", ":")) + ";\n")
    return path


def export_replay():
    cap    = P.load_capture(REPLAY_CSV)
    names  = sorted(set(cap.scenario.tolist()))
    replay = {
        "name":      os.path.basename(REPLAY_CSV),
        "scenarios": names,
        "ts":        cap.ts.tolist(),
        "raw":       [r(v, 2) for v in cap.raw],
        "label":     cap.label.tolist(),
        "scen":      [names.index(s) for s in cap.scenario],
    }
    path = os.path.join(WEB_DIR, "replay.js")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Auto-generated by training/export_web.py - DO NOT EDIT\n")
        f.write("// SYNTHETIC labelled test capture (label 1 = anomaly event)\n")
        f.write("var ESP32_REPLAY = " + json.dumps(replay, separators=(",", ":")) + ";\n")
    return path, len(cap.ts)


HIST_EDGES = np.arange(-4.0, 9.01, 0.25)        # log10(MSE) bins


def hist(mse):
    m = mse[~np.isnan(mse)]
    c, _ = np.histogram(np.log10(np.clip(m, 1e-4, 1e9)), bins=HIST_EDGES)
    return c.tolist()


def export_project():
    """Numbers for the explainer sections: data quality, training set, threshold, results."""
    layers, nmin, nscale, thr = P.load_model_headers(INCLUDE_DIR)
    out = {"captures": [], "training": [], "results": [], "hist": {}}

    normal_mse = []
    for cap in P.load_dir(os.path.join(HERE, "data", "normal")):
        feats, valid, _ = P.process_stream(cap.ts, cap.raw)
        contam = P.contamination_mask(feats, valid)
        keep   = valid & ~contam
        out["captures"].append(dict(name=cap.name, kind="normal", **P.raw_quality(cap),
                                    minutes=r((cap.ts[-1] - cap.ts[0]) / 60000, 1)))
        out["training"].append({"name": cap.name, "valid": int(valid.sum()),
                                "contaminated": int(contam.sum()), "kept": int(keep.sum())})
        normal_mse.append(P.reconstruction_mse(layers, nmin, nscale, feats[keep]))

    test_norm, test_anom = [], []
    for cap in P.load_dir(os.path.join(HERE, "data", "test")):
        out["captures"].append(dict(name=cap.name, kind="test", **P.raw_quality(cap),
                                    minutes=r((cap.ts[-1] - cap.ts[0]) / 60000, 1)))
        feats, valid, fault = P.process_stream(cap.ts, cap.raw)
        mse    = P.reconstruction_mse(layers, nmin, nscale, feats)
        _, led = P.run_detector(mse, valid, fault, thr)
        if cap.label is None:
            continue
        lab = cap.label.astype(bool)
        test_norm.append(mse[~lab])
        test_anom.append(mse[lab & (cap.scenario != "sensor_fault")])
        ev = P.evaluate_events(cap, led)
        out["results"].append({
            "name": cap.name,
            "events": [{"scenario": str(e["scenario"]), "detected": bool(e["detected"]),
                        "latency_ms": e["latency_ms"]} for e in ev["events"]],
            "false_alarms": ev["false_alarms"],
            "normal_minutes": r(ev["normal_hours"] * 60, 1),
        })

    out["hist"] = {
        "edges":        HIST_EDGES.tolist(),
        "normal_train": hist(np.concatenate(normal_mse)),
        "test_normal":  hist(np.concatenate(test_norm)),
        "test_anomaly": hist(np.concatenate(test_anom)),
    }
    path = os.path.join(WEB_DIR, "project.js")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Auto-generated by training/export_web.py - DO NOT EDIT\n")
        f.write("var ESP32_PROJECT = " + json.dumps(out, separators=(",", ":")) + ";\n")
    return path


def main():
    print("── Export web dashboard data ──")
    os.makedirs(WEB_DIR, exist_ok=True)
    print(f"  model   → {os.path.normpath(export_model())}")
    path, n = export_replay()
    print(f"  replay  → {os.path.normpath(path)} ({n} rows)")
    print(f"  project → {os.path.normpath(export_project())}")
    print("  Next: python verify_web.py")


if __name__ == "__main__":
    sys.exit(main())
